import fs from "node:fs";
import path from "node:path";
import assert from "node:assert/strict";
import { fileURLToPath } from "node:url";
import { createVerificationSuite, computeVerifiedBaselineSourceIdentity, createVerifiedBaseline, campaignResultsAreCurrent, createRegressionCampaign, exportRegressionCampaign, importRegressionCampaign, runRegressionCampaign, summarizeRegressionCampaign, verifyRegressionCampaign } from "../../dist-browser-test/ui/src/browser/index.js";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");
const source = JSON.parse(fs.readFileSync(path.join(root, "tests/fixtures/valid/scenario-normalized.json"), "utf8"));
let checks = 0;
const ok = (value, message) => { assert.ok(value, message); checks += 1; };
const eq = (actual, expected, message) => { assert.deepEqual(actual, expected, message); checks += 1; };
const baseline = await createVerifiedBaseline({ source, title: "Regression baseline", originType: "CANONICAL_SCENARIO", originId: source.scenarioId });
const suite = await createVerificationSuite({ title: "Primary suite", selectedFlowIds: [source.tests[0].id], assertions: [{ assertionId: "assertion-1", flowId: source.tests[0].id, type: "ENGINE_TEST_OUTCOME", expected: "SUCCESS" }] });
const sourceIdentity = await computeVerifiedBaselineSourceIdentity(source);
const candidateA = { candidateId: "candidate-a", title: "Candidate A", source: structuredClone(source), sourceIdentity };
const candidateB = { candidateId: "candidate-b", title: "Candidate B", source: structuredClone(source), sourceIdentity };
const campaign = await createRegressionCampaign({ title: "Baseline campaign", baseline, candidates: [candidateB, candidateA], suite });
eq(campaign.runOrder, ["baseline", "candidate-a", "candidate-b"], "campaign order is deterministic");
eq(campaign.status, "NOT RUN", "campaign starts not run");
const runnerCalls = [];
const runner = { run: async (candidateSource, flowId, sourceRevision) => { runnerCalls.push({ source: candidateSource, flowId, sourceRevision }); return { runId: `${candidateSource.scenarioId}:${sourceRevision}:${flowId}:${runnerCalls.length}`, sourceIdentity, sourceRevision, flowId, evaluation: { tests: [{ id: flowId, outcome: "TRUE" }], objectives: [], findings: [], completion: { truth: "TRUE" }, evidence: [] } }; } };
const completed = await runRegressionCampaign(campaign, runner);
eq(completed.status, "COMPLETE", "all subjects complete");
eq(completed.currentResults.map((item) => item.subjectId), ["baseline", "candidate-a", "candidate-b"], "baseline runs before candidates");
eq(runnerCalls.length, 3, "each subject gets a fresh Engine runner invocation");
ok(completed.currentResults.every((item) => item.run.historical), "results explicitly retain historical run marker");
ok(await campaignResultsAreCurrent(completed), "completed campaign results are current");
eq(summarizeRegressionCampaign(completed).baseline.PASS, 1, "summary is factual assertion count");
const roundtrip = await importRegressionCampaign(exportRegressionCampaign(completed));
ok(roundtrip.ok, "campaign export/import passes");
const tampered = structuredClone(completed); tampered.candidates[0].source.metadata.title = "changed";
const tamperedResult = await verifyRegressionCampaign(tampered);
ok(!tamperedResult.ok, "candidate source tamper fails closed");
const suiteTamper = structuredClone(completed); suiteTamper.suite.title = "changed";
const suiteTamperResult = await verifyRegressionCampaign(suiteTamper);
ok(!suiteTamperResult.ok, "suite change invalidates campaign identity");
const duplicate = await createRegressionCampaign({ title: "duplicate", baseline, candidates: [candidateA, { ...candidateA }], suite }).catch((error) => String(error));
ok(typeof duplicate === "string" && duplicate.includes("REGRESSION_CAMPAIGN_DUPLICATE_CANDIDATE"), "duplicate candidate fails closed");
let calls = 0;
const partial = await runRegressionCampaign(campaign, { run: async (...args) => { calls += 1; if (calls === 2) throw new Error("candidate failure"); return runner.run(...args); } });
eq(partial.status, "PARTIAL", "candidate failure produces explicit partial campaign");
eq(partial.currentResults.length, 1, "partial campaign does not fabricate remaining results");
const noScore = JSON.stringify(completed);
ok(!noScore.includes("score") && !noScore.includes("ranking") && !noScore.includes("bestCandidate"), "campaign contains no score/ranking/recommendation semantics");
console.log(`PASS v1.7 Dev2 Regression Campaign: ${checks} assertions.`);
