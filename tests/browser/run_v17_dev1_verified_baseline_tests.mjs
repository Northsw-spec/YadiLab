import fs from "node:fs";
import path from "node:path";
import assert from "node:assert/strict";
import { fileURLToPath } from "node:url";
import { archiveVerifiedBaseline, computeVerifiedBaselineSourceIdentity, createVerifiedBaseline, exportVerifiedBaseline, importVerifiedBaseline, inspectVerifiedBaseline, reproduceVerifiedBaseline, verifyVerifiedBaseline } from "../../dist-browser-test/ui/src/browser/index.js";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");
const source = JSON.parse(fs.readFileSync(path.join(root, "tests/fixtures/valid/scenario-normalized.json"), "utf8"));
let checks = 0;
const ok = (value, message) => { assert.ok(value, message); checks += 1; };
const eq = (actual, expected, message) => { assert.deepEqual(actual, expected, message); checks += 1; };
const sourceHash = await computeVerifiedBaselineSourceIdentity(source);

const first = await createVerifiedBaseline({ source, title: "Office baseline", description: "Exact source snapshot", originType: "EXPERIMENT_SOURCE", originId: "experiment-1", createdSequence: 7, verificationEvidence: { suiteId: "suite-1", suiteRunId: "run-1", sourceIdentity: sourceHash, sourceRevision: 2, historical: true } });
const second = await createVerifiedBaseline({ source, title: "Office baseline", originType: "CANONICAL_SCENARIO", originId: "scenario-1" });
eq(first.title, second.title, "duplicate titles are allowed");
ok(first.baselineId !== second.baselineId, "title is not baseline identity");
ok(first.canonicalSourceSnapshot !== source, "snapshot is cloned");
eq(first.status, "VERIFIED SNAPSHOT", "new baseline is a verified snapshot");
eq(inspectVerifiedBaseline(first).sourceIdentity, first.canonicalSourceIdentity, "inspection exposes factual source identity");
const exported = exportVerifiedBaseline(first);
const imported = await importVerifiedBaseline(exported);
ok(imported.ok, "export/import roundtrip passes");
eq(imported.ok && imported.value.baselineId, first.baselineId, "roundtrip preserves baseline identity");
const reproduced = await reproduceVerifiedBaseline(first, async (snapshot) => ({ scenarioId: snapshot.scenarioId, executed: true }));
ok(reproduced.ok, "reproduce validates then invokes normal runner");
eq(reproduced.ok && reproduced.result, { scenarioId: source.scenarioId, executed: true }, "reproduce returns fresh runner result");
const archived = await archiveVerifiedBaseline(first);
eq(archived.status, "ARCHIVED", "archive is explicit state transition");
const tampered = JSON.parse(exported); tampered.canonicalSourceSnapshot.resources[0].id = "tampered";
const tamperedResult = await verifyVerifiedBaseline(tampered);
ok(!tamperedResult.ok && tamperedResult.diagnostics.includes("VERIFIED_BASELINE_SOURCE_HASH_MISMATCH"), "tampered source fails closed");
const wrongHash = JSON.parse(exported); wrongHash.integrity.sourceSha256 = "0".repeat(64);
const wrongHashResult = await verifyVerifiedBaseline(wrongHash);
ok(!wrongHashResult.ok && wrongHashResult.diagnostics.includes("VERIFIED_BASELINE_SOURCE_INTEGRITY_METADATA_INVALID"), "wrong recorded hash fails closed");
const wrongSchema = JSON.parse(exported); wrongSchema.schemaVersion = "9.9.9";
const wrongSchemaResult = await verifyVerifiedBaseline(wrongSchema);
ok(!wrongSchemaResult.ok && wrongSchemaResult.diagnostics.includes("VERIFIED_BASELINE_VERSION_UNSUPPORTED"), "unknown schema fails closed");
const invalidJson = await importVerifiedBaseline("{");
ok(!invalidJson.ok && invalidJson.diagnostics.includes("VERIFIED_BASELINE_JSON_INVALID"), "invalid JSON fails closed");
const missing = await verifyVerifiedBaseline({ formatId: "infrastructure-cyber-lab.verified-baseline", schemaVersion: "0.1.0" });
ok(!missing.ok && missing.diagnostics.includes("VERIFIED_BASELINE_SOURCE_MISSING"), "missing source fails closed");
const staleEvidence = JSON.parse(exported); staleEvidence.verificationEvidence.historical = false;
const staleEvidenceResult = await verifyVerifiedBaseline(staleEvidence);
ok(!staleEvidenceResult.ok, "non-historical verification evidence is not accepted");
const notes = JSON.parse(exported); notes.userNotes.push("USER NOTE: investigate later");
const notesResult = await verifyVerifiedBaseline(notes);
ok(!notesResult.ok, "metadata tampering fails identity verification");
console.log(`PASS v1.7 Dev1 Verified Baseline: ${checks} assertions.`);
