import assert from "node:assert/strict";
import fs from "node:fs/promises";
import { createTroubleshootingCase, attachCaseRun } from "../../dist-browser-test/ui/src/browser/troubleshooting-case.js";
import { createSavedDiagnosticSession, exportSavedDiagnosticSession, importSavedDiagnosticSession, verifySavedDiagnosticSession, sessionArchiveLabel, sessionRunIsArchived } from "../../dist-browser-test/ui/src/browser/diagnostic-session.js";
const source = JSON.parse(await fs.readFile("tests/fixtures/valid/scenario-source.json", "utf8"));
const evidence = (revision, outcome) => ({ scenarioHash: "c".repeat(64), runtimeRevision: revision, flowId: "flow-1", outcome: { kind: outcome }, records: [{ eventId: `e-${revision}`, sequence: 1, runtimeRevision: revision, scenarioHash: "c".repeat(64), flowId: "flow-1", domain: "Outcome", eventType: "flow.outcome", sourceResourceId: "r1", truth: outcome, summary: outcome, provenance: "Engine", evidenceRefs: [] }] });
let value = await createTroubleshootingCase({ source, title: "Saved diagnostic session" });
value = await attachCaseRun(value, evidence(1, "DROP"), 0);
value = await attachCaseRun(value, evidence(2, "SUCCESS"), 1);
const runs = value.runs.map((run) => ({ run, evidence: evidence(run.runtimeRevision, run.outcome) }));
const session = await createSavedDiagnosticSession({ sessionId: value.caseId, case: value, runs });
const text = exportSavedDiagnosticSession(session);
const imported = await importSavedDiagnosticSession(text);
assert.equal(imported.ok, true);
assert.equal(imported.session.case.startingSource.scenarioId, source.scenarioId);
assert.equal(imported.session.runs.every(sessionRunIsArchived), true);
assert.equal(sessionArchiveLabel(imported.session.runs[0]), "ARCHIVED RUN");
const tampered = JSON.parse(text); tampered.runs[0].evidence.records[0].summary = "tampered";
assert.equal((await verifySavedDiagnosticSession(tampered)).ok, false);
const wrongVersion = JSON.parse(text); wrongVersion.schemaVersion = "9.9.9";
assert.equal((await verifySavedDiagnosticSession(wrongVersion)).ok, false);
const missingSource = JSON.parse(text); delete missingSource.case.startingSource;
assert.equal((await verifySavedDiagnosticSession(missingSource)).ok, false);
assert.match(text, /scenario-source|startingSource|scenarioId/);
assert.ok(!text.includes("/tmp/yadilab") && !text.includes("/home/daniel"));
console.log("PASS v1.5 Dev3 sessions: self-contained source, archived labels, export/import, integrity/tamper, unsupported/missing source and privacy");
