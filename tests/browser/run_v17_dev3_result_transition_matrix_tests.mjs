import fs from "node:fs";
import path from "node:path";
import assert from "node:assert/strict";
import { fileURLToPath } from "node:url";
import { buildResultTransitionMatrix, exportResultTransitionMatrix, filterResultTransitionMatrix, transitionIsRegressionOnly, verifyResultTransitionMatrix } from "../../dist-browser-test/ui/src/browser/index.js";
import { computeVerifiedBaselineSourceIdentity, createVerifiedBaseline, createVerificationSuite, createRegressionCampaign, runRegressionCampaign } from "../../dist-browser-test/ui/src/browser/index.js";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");
const source = JSON.parse(fs.readFileSync(path.join(root, "tests/fixtures/valid/scenario-normalized.json"), "utf8"));
let checks = 0;
const ok = (value, message) => { assert.ok(value, message); checks += 1; };
const eq = (actual, expected, message) => { assert.deepEqual(actual, expected, message); checks += 1; };
const baseline = await createVerifiedBaseline({ source, title: "Matrix baseline", originType: "CANONICAL_SCENARIO", originId: source.scenarioId });
const suite = await createVerificationSuite({ title: "Matrix suite", selectedFlowIds: [source.tests[0].id], assertions: [{ assertionId: "assertion-1", flowId: source.tests[0].id, type: "ENGINE_TEST_OUTCOME", expected: "SUCCESS" }] });
const sourceIdentity = await computeVerifiedBaselineSourceIdentity(source);
const candidate = { candidateId: "candidate-a", title: "Candidate A", source: structuredClone(source), sourceIdentity };
const campaign = await createRegressionCampaign({ title: "Matrix campaign", baseline, candidates: [candidate], suite });
let call = 0;
const runner = { run: async (_source, flowId, sourceRevision) => { call += 1; const outcome = call === 1 ? "TRUE" : "FALSE"; return { runId: `run-${call}`, sourceIdentity, sourceRevision, flowId, evaluation: { tests: [{ id: flowId, outcome }], objectives: [], findings: [], completion: { truth: "UNKNOWN" }, evidence: [] } }; } };
const completed = await runRegressionCampaign(campaign, runner);
const matrix = await buildResultTransitionMatrix(completed);
eq(matrix.rows.length, 1, "matrix has one assertion transition");
eq(matrix.rows[0].transition, "PASS→FAIL", "matrix records factual PASS to FAIL transition");
ok(matrix.rows[0].comparable, "same suite/flow/assertion is comparable");
ok(transitionIsRegressionOnly(matrix.rows[0]), "PASS to FAIL receives regression-only factual label");
eq(matrix.counts["PASS→FAIL"], 1, "raw transition count is explicit");
eq(filterResultTransitionMatrix(matrix, { transition: "PASS→FAIL" }).length, 1, "factual transition filter works without Engine run");
ok(!JSON.stringify(matrix).toLowerCase().includes("best"), "matrix does not rank candidates");
ok(!JSON.stringify(matrix).toLowerCase().includes("cause"), "matrix does not infer causality");
const roundtrip = await verifyResultTransitionMatrix(JSON.parse(exportResultTransitionMatrix(matrix)));
ok(roundtrip.ok, "matrix export/import integrity passes");
const bad = structuredClone(matrix);
bad.rows[0].regressionOnly = true;
bad.rows[0].transition = "FAIL→PASS";
const badResult = await verifyResultTransitionMatrix(bad);
ok(!badResult.ok && badResult.diagnostics.includes("RESULT_TRANSITION_MATRIX_FALSE_REGRESSION_LABEL"), "false regression label fails closed");
const stale = structuredClone(completed);
stale.candidates[0].source.metadata.title = "edited after run";
const staleMatrix = await buildResultTransitionMatrix(stale);
ok(staleMatrix.stale, "candidate source drift makes matrix historical/stale");
ok(staleMatrix.rows.every((row) => row.stale), "stale rows are explicitly marked");
console.log(`PASS v1.7 Dev3 Result Transition Matrix: ${checks} assertions.`);
