"""Independent ODF ZIP writer for real browser and import validation fixtures.

It deliberately does not use the implementation under test. Generated bytes
contain normal ODF mimetype and manifest metadata plus content.xml tables.
"""
from __future__ import annotations

import csv
import io
import zipfile
from xml.sax.saxutils import escape, quoteattr

from test_csv_import import DEV, PORTS, LINKS, ZONES

MIME = "application/vnd.oasis.opendocument.spreadsheet"
BASE_SHEETS = {"Devices":DEV, "Interfaces":PORTS, "Links":LINKS, "Zones":ZONES}
NS = (
    'xmlns:office="urn:oasis:names:tc:opendocument:xmlns:office:1.0" '
    'xmlns:table="urn:oasis:names:tc:opendocument:xmlns:table:1.0" '
    'xmlns:text="urn:oasis:names:tc:opendocument:xmlns:text:1.0"'
)


def _plain(value: str) -> str:
    return escape(value).replace("\n", "<text:line-break/>").replace("\t", "<text:tab/>")


def ods_parts(sheets=None, *, reorder=False, trailing=False, styles=False) -> dict[str, bytes]:
    data = dict(BASE_SHEETS if sheets is None else sheets)
    if reorder:
        data = dict(reversed(list(data.items())))
    sheet_xml = []
    for name, csv_data in data.items():
        records = list(csv.reader(io.StringIO(csv_data, newline="")))
        header = records[0] if records else []
        rows = []
        for index, columns in enumerate(records):
            cells = []
            for col, value in enumerate(columns):
                field = header[col] if col < len(header) else ""
                if value == "":
                    cells.append("<table:table-cell/>")
                elif index > 0 and field in ("x", "y"):
                    cells.append(f'<table:table-cell office:value-type="float" office:value={quoteattr(value)}><text:p>{_plain(value)}</text:p></table:table-cell>')
                elif index > 0 and field == "enabled":
                    cells.append(f'<table:table-cell office:value-type="boolean" office:boolean-value={quoteattr(value)}/>')
                else:
                    cells.append(f'<table:table-cell office:value-type="string"><text:p>{_plain(value)}</text:p></table:table-cell>')
            if trailing:
                cells.append('<table:table-cell table:number-columns-repeated="1024"/>')
            rows.append(f'<table:table-row>{"".join(cells)}</table:table-row>')
        if trailing:
            rows.append('<table:table-row table:number-rows-repeated="500"><table:table-cell table:number-columns-repeated="1024"/></table:table-row>')
        sheet_xml.append(
            f'<table:table table:name={quoteattr(name)}>'
            '<table:table-column table:number-columns-repeated="1024"/>'
            + "".join(rows) + '</table:table>')
    optional_style = (
        '<office:automatic-styles><style:style xmlns:style="urn:oasis:names:tc:opendocument:xmlns:style:1.0" style:name="ta1" style:family="table"/></office:automatic-styles>'
        if styles else '')
    content = (
        '<?xml version="1.0" encoding="UTF-8"?>'
        f'<office:document-content {NS} office:version="1.2">'
        f'{optional_style}'
        '<office:body><office:spreadsheet>'
        + "".join(sheet_xml) + '</office:spreadsheet></office:body>'
        '</office:document-content>'
    )
    manifest = (
        '<?xml version="1.0" encoding="UTF-8"?>'
        '<manifest:manifest xmlns:manifest="urn:oasis:names:tc:opendocument:xmlns:manifest:1.0" manifest:version="1.2">'
        f'<manifest:file-entry manifest:full-path="/" manifest:media-type="{MIME}"/>'
        '<manifest:file-entry manifest:full-path="content.xml" manifest:media-type="text/xml"/>'
        '</manifest:manifest>'
    )
    return {
        "mimetype":MIME.encode("ascii"),
        "META-INF/manifest.xml":manifest.encode("utf-8"),
        "content.xml":content.encode("utf-8"),
    }


def zip_parts(parts: dict[str, bytes]) -> bytes:
    result = io.BytesIO()
    with zipfile.ZipFile(result, "w") as z:
        z.writestr("mimetype", parts["mimetype"], compress_type=zipfile.ZIP_STORED)
        for filename, data in parts.items():
            if filename != "mimetype":
                z.writestr(filename, data, compress_type=zipfile.ZIP_DEFLATED)
    return result.getvalue()


def make_ods(sheets=None, *, reorder=False, trailing=False, styles=False) -> bytes:
    return zip_parts(ods_parts(sheets, reorder=reorder, trailing=trailing, styles=styles))
