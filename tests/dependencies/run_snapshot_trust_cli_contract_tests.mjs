import fs from "node:fs";
import path from "node:path";
import assert from "node:assert/strict";
import { fileURLToPath } from "node:url";
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");
const cli = fs.readFileSync(path.join(root, "scripts/manage_offline_snapshot_trust.mjs"), "utf8");
let checks = 0; const ok=(v,m)=>{assert.ok(v,m);checks++;};
ok(cli.includes("EXPECTED_KEY_ID"), "staging CLI requires explicit expected key fingerprint");
ok(cli.includes('command === "stage" || command === "onboard"'), "legacy onboard command aliases fail-closed staging semantics");
ok(cli.includes("input must resolve outside the application source checkout") && cli.includes("public key onboarding"), "public-key input must be external to checkout");
ok(cli.includes("input must resolve outside the application source checkout") && cli.includes("private key activation"), "activation private-key input must be external to checkout");
ok(cli.includes("fs.realpathSync(requested)"), "key inputs resolve symlinks before source-boundary checks");
ok(cli.includes("activateSnapshotTrustKey"), "CLI exposes explicit proof-of-possession activation path");
ok(cli.includes("private key activation permissions must be 0400 or 0600"), "activation enforces restrictive private-key permissions");
ok(cli.includes("revokeSnapshotTrustKey"), "CLI exposes explicit revocation path");
ok(cli.includes("process.exit(77)"), "trust lifecycle failures are fail-closed exit 77");
ok(!cli.includes("PRIVATE KEY-----"), "CLI embeds no private key material");
ok(cli.includes("LABEL"), "staging requires operator-readable key label");
console.log(`PASS snapshot trust CLI contract suite: ${checks} assertions.`);
