import fs from "node:fs"; import path from "node:path"; import assert from "node:assert/strict"; import {fileURLToPath} from "node:url";
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),"../.."); const s=fs.readFileSync(path.join(root,"scripts/install_offline_browser_dependencies.sh"),"utf8");
let checks=0; const ok=(v,m)=>{assert.ok(v,m);checks++;};
const stage=s.indexOf('node "$root/scripts/stage_source_checkout.mjs" "$root" "$stage"');
const cdStage=s.indexOf('cd "$stage"');
const install=s.indexOf('npm ci --offline --cache "$cache/npm-cache" --no-audit --no-fund');
const build=s.indexOf('node scripts/build_browser_app.mjs');
const verify=s.indexOf('node scripts/verify_browser_release.mjs',build);
const dist=s.indexOf('bash scripts/build_loopback_distribution.sh');
const distHash=s.indexOf('(cd distribution/linux-x86_64 && sha256sum -c SHA256SUMS.txt)',dist);
const promote=s.indexOf('node "$root/scripts/promote_offline_browser_build.mjs" "$root" "$stage"');
const recover=s.indexOf('node "$root/scripts/recover_offline_browser_build_transaction.mjs" "$root"');
ok(recover>=0,"interrupted transaction recovery runs on installer entry");
ok(stage>recover,"source stage is created after recovery/preflight");
ok(cdStage>stage,"installer switches into isolated stage");
ok(install>cdStage,"npm ci runs only inside isolated stage");
ok(build>install,"browser build runs after staged npm ci");
ok(verify>build,"staged browser release is verified");
ok(dist>verify,"loopback distribution builds only after browser verification");
ok(distHash>dist,"staged distribution hashes verify before promotion");
ok(promote>distHash,"live checkout promotion occurs only after every staged build gate passes");
ok(!s.includes('cp "$cache/package-lock.json" ./package-lock.json'),"installer no longer writes snapshot lock into live checkout before build");
console.log(`PASS offline install staging contract suite: ${checks} assertions.`);
